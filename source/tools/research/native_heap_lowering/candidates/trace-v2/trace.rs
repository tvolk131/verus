 assert(s25.ok);
 let s26=step(s25,Op::Clear(204));
 assert(s26.ok);
 let s27=step(s26,Op::Num(10001,0));
 assert(s27.ok);
 let s28=step(s27,Op::Test(10001,0));
 assert(s28.ok);
 let s29=step(s28,Op::Clear(206));
 assert(s29.ok);
 let s30=step(s29,Op::Unwrap(206,203));
 assert(s30.ok);
