#!/usr/bin/env python3
"""Prepare final private trials and exact controls before their execution."""
import hashlib,json,sys
from pathlib import Path
sys.dont_write_bytecode=True
HERE=Path(__file__).resolve().parent
from fidelity import check

def main():
 out=Path(sys.argv[1]).resolve();out.mkdir(exist_ok=False)
 c=(HERE/'cache_component.rs').read_text();check(HERE/'cache_component.rs')
 cases=[]
 def put(n,t,infer=False,extra=None,cache=None):
  p=out/(n+'.rs');p.write_text(t)
  cases.append(dict(name=n,source=str(p),source_sha256=hashlib.sha256(p.read_bytes()).hexdigest(),infer=infer,extra=extra or [],cache=cache or n))
 for n,enabled in [('cache-enabled-cold',True),('cache-enabled-warm',True),('cache-assistance-off',False)]:
  put(n,c,enabled,cache='cache-enabled' if enabled else None)
 variants={
 'cache-wrong-index-head':c.replace('self.idx[0] = idx;','self.idx[0] = 0;'),
 'cache-short-index-shift':c.replace('self.idx.copy_within(0..CACHE_LEN - 1, 1);','self.idx.copy_within(0..CACHE_LEN - 2, 1);'),
 'cache-invalid-initial-index':c.replace('idx: [0; CACHE_LEN], items:', 'idx: [1; CACHE_LEN], items:'),
 'cache-false-preservation-property':c.replace('ensures cache_consistent(after, borrows),','ensures cache_consistent(after, borrows), after.idx[0] as int == idx as int + 1,')}
 for n,s in variants.items():
  if s==c:raise ValueError('missing mutation '+n)
  put(n,s,True)
 # Primary source fixtures freshly generated by prepare.py, with corrected cfg.
 import subprocess
 subprocess.run([sys.executable,'-O',str(HERE/'prepare.py'),str(out/'literal-fixtures')],check=True)
 t=(out/'literal-fixtures/literal-enabled.rs').read_text()
 for n,enabled in [('literal-enabled-on',True),('literal-enabled-off',False)]:
  put(n,t,enabled,['--cfg','feature="stack-cache"'])
 for n in ['reverse-laws-diagnostic','reverse-for-diagnostic']:
  p=Path('/tmp/native-miri-find-granting-20261110-impl-init005')/(n+'.rs')
  # Named completed own artifacts only; exact bytes become frozen inputs here.
  put(n,p.read_text(),True)
 (out/'plan.json').write_text(json.dumps(dict(schema=1,epoch=out.name,cases=cases),indent=2)+'\n')
 print(out/'plan.json')
if __name__=='__main__':main()
